function cookie(userId: string): string {
  return `swerv_access=${createAccessToken(userId)}`;
}

async function createDispatchRequest() {
  const response = await request(app)
    .post('/api/dispatch-requests')
    .set('Cookie', adminCookie)
    .send(validRequest)
    .expect(201);
  return response.body.data.dispatchRequest;
}

async function createAgent() {
  return Agent.create({
    agentCode: `AGT-${new mongoose.Types.ObjectId().toString().slice(-8)}`,
    name: 'Taylor Driver',
    email: `prediction-driver-${new mongoose.Types.ObjectId()}@example.com`,
    phone: '+1 555 111 2222',
    vehicle: {
      vehicleType: 'van',
      registrationNumber: `SW-${new mongoose.Types.ObjectId().toString().slice(-6)}`,
      manufacturer: 'Ford',
      model: 'Transit',
    },
    capacity: { maxOrders: 4 },
    capabilities: ['parcel_delivery', 'express_delivery'],
  });
}

async function assignRequest(dispatchRequestId: string, agentId: string, cookieValue = adminCookie) {
  await request(app)
    .patch(`/api/dispatch-requests/${dispatchRequestId}/assignment`)
    .set('Cookie', cookieValue)
    .send({ agentId })
    .expect(200);
}

function stubPythonResponse(body: unknown, status = 200) {
  const fetchMock = vi.fn().mockResolvedValue(new Response(JSON.stringify(body), {
    status,
    headers: { 'content-type': 'application/json' },
  }));
  vi.stubGlobal('fetch', fetchMock);
  return fetchMock;
}

